#!/usr/bin/env node

// The in-house CSHL functional-curation set: community submissions made through the
// "Curate Gene Function" Google Form linked from every gene page's Curated publications tab.
//
// This used to fetch https://dev.gramene.org/cshl_curated_genes.json. That URL is on brie.cshl.edu,
// a host this build does not control, there is no generator for its contents anywhere on squam, and
// its Last-Modified sat at 2024-10-10 with 158 entries while the sheet behind the form grew to 1,221
// rows -- so two years of curation the live site solicited never reached the site. The feed is now a
// tracked in-tree artifact regenerated by build/stages/29_curated_sources.sh, which makes staleness
// visible in git rather than in an HTTP header and makes the build reproducible offline.
//
// All behaviour lives in curated_source.js, shared with rapdb.js.

module.exports = function () {
  return require('./curated_source')({
    label: 'curated',
    source: 'CSHL',
    urls: ['https://dev.gramene.org/cshl_curated_genes.json'],
    refTextField: 'description'
  });
};
