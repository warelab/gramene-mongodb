#!/usr/bin/env python3
"""gen_legume_id_sql.py — emit SQL that renames the Medicago/Lablab generic Ensembl ids to the
community ids, in the core databases and in compara.

Reads legume_community_ids_features.tsv (built by build_legume_id_map.py) and writes one
self-contained .sql per target database.

WHY SELF-CONTAINED INSERTS RATHER THAN "LOAD DATA LOCAL INFILE"
LOAD DATA LOCAL needs local_infile enabled on client and server, which is often off. Embedding the
mapping as INSERT batches means the scripts need nothing beyond CREATE/INSERT/UPDATE/DROP.

WHAT THE TARGET LOOKS LIKE  (checked on colden, 2026-10-09)
  * every table is MyISAM, so there is NO transaction and NO rollback -- the backup is the only
    undo, and each script says so at the top
  * MySQL 5.5.57, so no REGEXP_REPLACE and no CTEs; multi-table UPDATE ... JOIN is fine
  * compara gene_member/seq_member carry a UNIQUE (genome_db_id, stable_id) index. The rename
    cannot transiently violate it because the old and new id spaces are disjoint: old ids are
    geneN / rnaN / mRNAN / cds:mRNAN / RHN*.1, new ids are MtrunA17_* / Labpu*.
  * exon.stable_id is always '<transcript_stable_id>-E<n>' (verified 194,395/194,395 and
    145,419/145,419) and no exon belongs to more than one transcript, so exons are renamed from
    the transcript map rather than needing their own.

MEDICAGO TRANSLATIONS -- A JUDGEMENT CALL, MARKED IN THE SCRIPT
Ensembl currently stores medicago translations as GenBank protein accessions (RHN52259.1). Those
are real, citable INSDC identifiers -- arguably better than a locus-tag-derived id. Renaming them
buys consistency with the gene/transcript and with the search index, which is what was asked for,
but it does discard a citable id from the primary field. That section is fenced so it can be
skipped, and the accession is preserved in legume_community_ids_features.tsv as community_id_alt.
"""
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
FEAT = os.environ.get('FEAT_TSV', os.path.join(HERE, 'legume_community_ids_features.tsv'))
OUTDIR = os.environ.get('SQL_OUT', os.path.join(HERE, 'sql'))
BATCH = 500

MT_CORE = 'medicago_truncatula_core_70_116_3'
LP_CORE = 'lablab_purpureus_gca030347555v1cm_core_70_116_1'
COMPARA = 'ensembl_compara_plants_70_116'
GDB = {'medicago_truncatula': 2282, 'lablab_purpureus': 2308}

SPECIES_CORE = {'medicago_truncatula': MT_CORE, 'lablab_purpureus': LP_CORE}


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


def load():
    m = defaultdict(lambda: defaultdict(list))   # species -> feature_type -> [(old, new)]
    with open(FEAT, errors='replace') as fh:
        hdr = fh.readline().rstrip('\n').split('\t')
        ix = {c: i for i, c in enumerate(hdr)}
        for line in fh:
            f = line.rstrip('\n').split('\t')
            if len(f) < len(hdr):
                continue
            sp, ft = f[ix['species']], f[ix['feature_type']]
            old, new = f[ix['ensembl_id']], f[ix['community_id']]
            if old and new and old != new:
                m[sp][ft].append((old, new))
            if ft == 'translation' and old:
                m[sp]['translation_parent'].append((f[ix['parent_ensembl_gene']], old))
    return m


def staging(out, name, pairs):
    """A keyed staging table, so the UPDATE joins by index rather than scanning."""
    out.write("DROP TABLE IF EXISTS %s;\n" % name)
    out.write("CREATE TABLE %s (\n"
              "  old_id VARCHAR(128) NOT NULL,\n"
              "  new_id VARCHAR(128) NOT NULL,\n"
              "  PRIMARY KEY (old_id)\n"
              ") ENGINE=MyISAM DEFAULT CHARSET=latin1;\n" % name)
    for i in range(0, len(pairs), BATCH):
        chunk = pairs[i:i + BATCH]
        out.write("INSERT INTO %s (old_id,new_id) VALUES\n" % name)
        out.write(",\n".join("('%s','%s')" % (esc(o), esc(n)) for o, n in chunk))
        out.write(";\n")
    out.write("-- staged %d rows into %s\n\n" % (len(pairs), name))


HEADER = """-- ---------------------------------------------------------------------------
-- {title}
--
--   database: {db}  (on colden)
--   generated by gramene-mongodb/search/gen_legume_id_sql.py
--
-- WHY
-- Ensembl Plants imported these annotations using the GFF3's file-local `ID=` attribute
-- (ID=gene0, ID=rna0) instead of the stable identifier the submission carries elsewhere, so every
-- feature is named geneNNNN / rnaNNNN / mRNANNNN / cds:mRNANNNN. Those ids are not what legume
-- researchers cite, and because Gramene keys gene documents on the stable id, medicago and lablab
-- collide on 24,925 of them. Ensembl Plants is frozen; Gramene fixes this and reports upstream.
--
-- The community ids come from:
--   medicago -- /locus_tag in the INSDC submission (MtrunA17_Chr4g0000001), the MtrunA17r5.0-ANR
--               scheme from the Toulouse portal. Joined via the GenBank protein accession that
--               Ensembl kept as its translation stable id, so the mapping is exact.
--   lablab   -- the GFF3 Name= attribute (Labpu01g000050) from the LegumeInfo copy of the ILRI
--               annotation, same assembly (GCA_030347555.1 is cv. Highworth / ILRI_Lpur). Joined
--               on representative-mRNA coordinates.
--
-- !! NO ROLLBACK !!  Every table here is MyISAM, so there is no transaction. The backup below is
-- the only undo. Take it, and verify it, before running anything.
--
--   mysqldump -h colden -u <writer> -p {db} {tables} \\
--     | gzip > {db}.pre-community-ids.sql.gz
--
-- The script is idempotent: each UPDATE joins on the OLD id, and the old and new id spaces are
-- disjoint, so a second run matches nothing.
-- ---------------------------------------------------------------------------

USE {db};

"""


# How to recognise an id this script has ALREADY produced. Species-specific on purpose: lablab's
# 533 tRNA genes legitimately arrive with native Labpu_tRNA* ids (they came from a separate GFF3
# whose ID= attribute was the real one), so a blanket LIKE 'Labpu%' counts them as already-renamed
# and would abort a first run. The ids this script writes are Labpu<2 digits>g<6 digits>.
DONE_PRED = {
    'medicago_truncatula': "stable_id LIKE 'MtrunA17!_%' ESCAPE '!'",
    'lablab_purpureus': "stable_id REGEXP '^Labpu[0-9]'",
}


def write_core(species, path):
    db = SPECIES_CORE[species]
    m = MAP[species]
    done = DONE_PRED[species]
    genes, txs, tls = m['gene'], m['transcript'], m['translation']
    with open(path, 'w') as out:
        out.write(HEADER.format(title='Restore community gene/transcript/translation/exon ids',
                                db=db, tables='gene transcript translation exon'))

        out.write("-- --- 1. pre-flight ------------------------------------------------------\n")
        out.write("""SELECT 'gene' AS tbl, COUNT(*) AS total,
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%') AS generic,
       SUM({done}) AS already_renamed
  FROM gene
UNION ALL SELECT 'transcript', COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%'),
       SUM({done}) FROM transcript
UNION ALL SELECT 'translation', COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%' OR stable_id REGEXP '^[A-Z]{{3}}[0-9]+\\\\.[0-9]+$'),
       SUM({done}) FROM translation
UNION ALL SELECT 'exon', COUNT(*),
       SUM(stable_id LIKE '%-E%'), SUM({done}) FROM exon;
-- 'generic' must equal the expected row counts in section 3, and 'already_renamed' must be 0.
-- If already_renamed is non-zero the rename has run before; the UPDATEs are idempotent so a
-- re-run is harmless, but stop and find out why first.
""".format(done=done))
        out.write("-- --- 2. stage the mappings ---------------------------------------------\n")
        staging(out, 'gramene_gene_map', genes)
        staging(out, 'gramene_tx_map', txs)
        if species == 'medicago_truncatula':
            out.write("-- Medicago translations are currently GenBank protein accessions (RHN*.1),\n"
                      "-- which are citable INSDC ids. Renaming them gives consistency with the gene,\n"
                      "-- the transcript and the search index, but drops a citable id from the primary\n"
                      "-- field; the accession stays available in legume_community_ids_features.tsv as\n"
                      "-- community_id_alt. To KEEP the accessions, delete section 3c below and skip\n"
                      "-- this staging block.\n")
        staging(out, 'gramene_tl_map', tls)

        out.write("-- --- 3. rename ---------------------------------------------------------\n")
        out.write("-- 3a. genes\n"
                  "UPDATE gene g JOIN gramene_gene_map m ON m.old_id = g.stable_id\n"
                  "   SET g.stable_id = m.new_id;          -- expect %d rows\n\n" % len(genes))
        out.write("-- 3b. transcripts\n"
                  "UPDATE transcript t JOIN gramene_tx_map m ON m.old_id = t.stable_id\n"
                  "   SET t.stable_id = m.new_id;          -- expect %d rows\n\n" % len(txs))
        out.write("-- 3c. translations\n"
                  "UPDATE translation p JOIN gramene_tl_map m ON m.old_id = p.stable_id\n"
                  "   SET p.stable_id = m.new_id;          -- expect %d rows\n\n" % len(tls))
        out.write("""-- 3d. exons. exon.stable_id is always '<transcript_stable_id>-E<n>' (verified on every row
-- in this database) and no exon belongs to two transcripts, so the transcript map renames them.
-- Driving from exon with an indexed probe into gramene_tx_map keeps this an index lookup per row
-- rather than a scan; SUBSTRING_INDEX is on the exon side deliberately.
UPDATE exon e
  JOIN gramene_tx_map m ON m.old_id = SUBSTRING_INDEX(e.stable_id, '-E', 1)
   SET e.stable_id = CONCAT(m.new_id, '-E', SUBSTRING_INDEX(e.stable_id, '-E', -1))
 WHERE e.stable_id LIKE '%-E%';

""")
        out.write("-- --- 4. verify ---------------------------------------------------------\n")
        out.write("""SELECT 'gene' AS tbl, COUNT(*) AS total,
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%') AS still_generic,
       COUNT(DISTINCT stable_id) AS distinct_ids FROM gene
UNION ALL SELECT 'transcript', COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%'),
       COUNT(DISTINCT stable_id) FROM transcript
UNION ALL SELECT 'translation', COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%'),
       COUNT(DISTINCT stable_id) FROM translation
UNION ALL SELECT 'exon', COUNT(*), 0, COUNT(DISTINCT stable_id) FROM exon;
-- still_generic must be 0 everywhere, and distinct_ids must equal total.

-- every exon prefix must resolve to its own transcript again
SELECT COUNT(*) AS exons_whose_prefix_is_not_their_transcript
  FROM exon e
  JOIN exon_transcript et ON et.exon_id = e.exon_id
  JOIN transcript t ON t.transcript_id = et.transcript_id
 WHERE SUBSTRING_INDEX(e.stable_id, '-E', 1) <> t.stable_id;
-- expect 0

""")
        out.write("-- --- 5. clean up ------------------------------------------------------\n"
                  "DROP TABLE gramene_gene_map;\nDROP TABLE gramene_tx_map;\nDROP TABLE gramene_tl_map;\n")
    return len(genes), len(txs), len(tls)


def write_compara(path):
    # compara holds only the CODING subset: gene_member is 44,450 for medicago and 24,971 for
    # lablab, exactly their translation counts. Staging all 75,711 genes would still be correct
    # (the extra rows simply match nothing) but it would make the expected row counts in the
    # script wrong, which is worse than useless in a verification step. So the gene map is
    # restricted to genes that have a translation.
    gene_pairs, seq_pairs = [], []
    for sp, gdb in GDB.items():
        coding = {g for g, _ in MAP[sp]['translation_parent']}
        for old, new in MAP[sp]['gene']:
            if old in coding:
                gene_pairs.append((gdb, old, new))
        for old, new in MAP[sp]['translation']:
            seq_pairs.append((gdb, old, new))
    with open(path, 'w') as out:
        out.write(HEADER.format(title='Restore community ids for medicago + lablab members',
                                db=COMPARA, tables='gene_member seq_member'))
        out.write("""-- SCOPE IN COMPARA
-- Only gene_member.stable_id and seq_member.stable_id hold these ids. Checked and NOT affected:
--   hmm_curated_annot                 0 rows
--   seq_member_projection_stable_id   0 rows
--   stable_id_history                 holds gene-TREE ids (EPlGT*); 0 rows match a generic id
--   family                            2 rows, unrelated
--   gene_member.display_label / seq_member.display_label
--                                     real gene symbols (CYP72A68, NF-YB1, ndhE); 0 match generic
-- homology_member and the tree tables join on numeric member ids, so they are unaffected.
--
-- gene_member holds 14.5M rows and seq_member 17.5M, so every statement is restricted by
-- genome_db_id (2282 medicago, 2308 lablab) and joins the staging table by its primary key.
-- gene_member.stable_id maps from the GENE ids; seq_member.stable_id from the TRANSLATION ids,
-- which is what compara stores for protein members.

""")
        out.write("-- --- 1. pre-flight ------------------------------------------------------\n")
        out.write("""SELECT 'gene_member' AS tbl, genome_db_id, COUNT(*) AS total,
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%') AS generic
  FROM gene_member WHERE genome_db_id IN (2282,2308) GROUP BY genome_db_id
UNION ALL
SELECT 'seq_member', genome_db_id, COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%' OR stable_id REGEXP '^[A-Z]{3}[0-9]+\\\\.[0-9]+$')
  FROM seq_member WHERE genome_db_id IN (2282,2308) GROUP BY genome_db_id;

""")
        out.write("-- --- 2. stage the mappings (genome_db_id included: the generic ids are NOT\n"
                  "--        unique across the two genomes, which is the whole defect) ---------\n")
        for name, pairs in (('gramene_cmp_gene_map', gene_pairs), ('gramene_cmp_seq_map', seq_pairs)):
            out.write("DROP TABLE IF EXISTS %s;\n" % name)
            out.write("CREATE TABLE %s (\n"
                      "  genome_db_id INT NOT NULL,\n"
                      "  old_id VARCHAR(128) NOT NULL,\n"
                      "  new_id VARCHAR(128) NOT NULL,\n"
                      "  PRIMARY KEY (genome_db_id, old_id)\n"
                      ") ENGINE=MyISAM DEFAULT CHARSET=latin1;\n" % name)
            for i in range(0, len(pairs), BATCH):
                chunk = pairs[i:i + BATCH]
                out.write("INSERT INTO %s (genome_db_id,old_id,new_id) VALUES\n" % name)
                out.write(",\n".join("(%d,'%s','%s')" % (g, esc(o), esc(n)) for g, o, n in chunk))
                out.write(";\n")
            out.write("-- staged %d rows into %s\n\n" % (len(pairs), name))

        out.write("-- --- 3. rename ---------------------------------------------------------\n")
        # One statement per genome, with an explicit genome_db_id predicate. Restricting it only
        # inside the JOIN condition is NOT sargable: MySQL 5.5 then full-scans gene_member (14.5M
        # rows) and seq_member (17.5M) probing the staging table per row, and because both are
        # MyISAM the write lock blocks every reader meanwhile. Both tables carry UNIQUE KEY
        # genome_db_stable_id (genome_db_id, stable_id), so the predicate makes each statement an
        # index range over just that genome's rows.
        for tbl, alias, mapname, which in (('gene_member', 'gm', 'gramene_cmp_gene_map', gene_pairs),
                                           ('seq_member', 'sm', 'gramene_cmp_seq_map', seq_pairs)):
            for sp, gdb in sorted(GDB.items(), key=lambda kv: kv[1]):
                n_rows = sum(1 for g, _, _ in which if g == gdb)
                out.write("UPDATE %s %s\n"
                          "  JOIN %s m\n"
                          "    ON m.genome_db_id = %s.genome_db_id AND m.old_id = %s.stable_id\n"
                          "   SET %s.stable_id = m.new_id\n"
                          " WHERE %s.genome_db_id = %d;    -- %s, expect %d rows\n\n"
                          % (tbl, alias, mapname, alias, alias, alias, alias, gdb, sp, n_rows))

        out.write("-- --- 4. verify ---------------------------------------------------------\n")
        out.write("""SELECT 'gene_member' AS tbl, genome_db_id, COUNT(*) AS total,
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%') AS still_generic
  FROM gene_member WHERE genome_db_id IN (2282,2308) GROUP BY genome_db_id
UNION ALL
SELECT 'seq_member', genome_db_id, COUNT(*),
       SUM(stable_id REGEXP '^(gene|rna|mRNA)[0-9]+$' OR stable_id LIKE 'cds:%' OR stable_id REGEXP '^[A-Z]{{3}}[0-9]+\\\\.[0-9]+$')
  FROM seq_member WHERE genome_db_id IN (2282,2308) GROUP BY genome_db_id;
-- still_generic must be 0 for both genomes in both tables.

-- and compara must now agree with the cores
SELECT COUNT(*) AS gene_members_not_matching_core
  FROM gene_member gm
  LEFT JOIN {mt}.gene g ON g.stable_id = gm.stable_id
 WHERE gm.genome_db_id = 2282 AND g.gene_id IS NULL;
-- expect 0

SELECT COUNT(*) AS gene_members_not_matching_core
  FROM gene_member gm
  LEFT JOIN {lp}.gene g ON g.stable_id = gm.stable_id
 WHERE gm.genome_db_id = 2308 AND g.gene_id IS NULL;
-- expect 0

""".format(mt=MT_CORE, lp=LP_CORE))
        out.write("-- --- 5. clean up ------------------------------------------------------\n"
                  "DROP TABLE gramene_cmp_gene_map;\nDROP TABLE gramene_cmp_seq_map;\n")
    return len(gene_pairs), len(seq_pairs)


MAP = load()
if __name__ == '__main__':
    os.makedirs(OUTDIR, exist_ok=True)
    for sp in ('medicago_truncatula', 'lablab_purpureus'):
        p = os.path.join(OUTDIR, 'fix_%s_core_ids.sql' % sp.split('_')[0])
        g, t, l = write_core(sp, p)
        sys.stderr.write('%-22s genes=%d transcripts=%d translations=%d -> %s (%.1f MB)\n'
                         % (sp, g, t, l, p, os.path.getsize(p) / 1e6))
    p = os.path.join(OUTDIR, 'fix_compara_ids.sql')
    gm, sm = write_compara(p)
    sys.stderr.write('%-22s gene_member=%d seq_member=%d -> %s (%.1f MB)\n'
                     % (COMPARA, gm, sm, p, os.path.getsize(p) / 1e6))
