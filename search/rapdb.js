#!/usr/bin/env node

// RAP-DB's curated gene list for Oryza sativa japonica -- symbols, full names, PO/TO terms and
// structured PubMed references, keyed on the RAP locus ids (Os01g0100100) that are already this
// build's rice gene stable ids, so no id mapping is needed.
//
// Source history. The code once carried rapdb.dna.affrc.go.jp, which is DEAD (the host does not
// answer at all), overwritten on the next line by a mirror on dev.gramene.org -- a host this build
// does not control, holding a copy of the same upstream file. Both are gone: the feed is now the
// tracked in-tree artifact rapdb_curated_genes.json, regenerated by
// build/stages/29_curated_sources.sh from naro.go.jp, which stays here as the fallback only.
// Same treatment, and the same reasoning, as curated.js.
//
// All behaviour lives in curated_source.js, shared with curated.js.

module.exports = function () {
  return require('./curated_source')({
    label: 'rapdb',
    source: 'rap-db',
    localFile: 'rapdb_curated_genes.json',
    // Upstream, as the fallback only. Fetching this live during decorate is what the tracked
    // artifact replaces: a transient failure returns an EMPTY lut, which silently drops every
    // RAP-DB name, synonym and reference from the build instead of failing it -- this URL answered
    // 6,747 loci and then 0 within minutes while that was being measured. The dev.gramene.org copy
    // that used to sit here was a mirror of this same file on a host this build does not control,
    // and is deliberately gone: the in-pipeline artifact is the only local copy wanted.
    urls: ['https://rapdb.dna.naro.go.jp/curated_genes/curated_genes.json'],
    refTextField: 'title'
  });
};
