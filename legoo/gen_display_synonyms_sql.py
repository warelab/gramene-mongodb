#!/usr/bin/env python3
"""gen_display_synonyms_sql.py -- make the curated acronym searchable for genes that kept their
own display name.

WHY THIS IS NEEDED
03_legoo_load.sql deliberately does not overwrite an existing display name, so for 202 genes the
LeGOO xref exists but is not the gene's display_xref. That is the right call for display -- but
dump_genes.js collects synonyms ONLY from the display xref:

    JOIN xref x ON x.xref_id = g.display_xref_id
    LEFT JOIN external_synonym es ON es.xref_id = x.xref_id

so those genes' curated acronyms never reach the search index. Measured: 202 acronyms plus 42
alternative spellings = 244 searchable values silently dropped on a re-dump.

This attaches them as external_synonym rows on the gene's EXISTING display xref, which is where the
dump will find them. After this, the core is the complete source of truth: re-dumping medicago
reproduces every name, description and synonym, and patch_search_genes.js becomes unnecessary
rather than merely redundant.

The samples make the case -- these are different community names for one gene, and both should
find it:
    LEC5 -> MtLEC5      PHAN -> MtAS1      aos -> MtAOS1

INSERT IGNORE because external_synonym's PRIMARY KEY is (xref_id, synonym) and 138 synonym rows
already exist on those xrefs; pairs already present are skipped at generation time too, so the
generated revert deletes exactly what the load added and nothing else.

usage: gen_display_synonyms_sql.py [--core <db>] [--out <dir>]
"""
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CORE = 'medicago_truncatula_core_70_116_3'
TSV = os.path.join(HERE, 'legoo_genes.tsv')


def mysql(sql, db):
    cmd = ['mysql', '-h', os.environ['MYSQL_HOST'], '-u', os.environ['MYSQL_USER'],
           '-p' + os.environ['MYSQL_PASS'], '-N', '-s', '-D', db, '-e', sql]
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                         universal_newlines=True)
    out, err = p.communicate()
    if p.returncode:
        sys.exit('mysql failed: ' + err.strip())
    return [l.split('\t') for l in out.splitlines()]


def q(s):
    s = ''.join(ch for ch in s if ord(ch) >= 32)
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    args = sys.argv[1:]
    core, outdir = DEFAULT_CORE, os.path.join(HERE, 'sql')
    if '--core' in args:
        i = args.index('--core'); core = args[i + 1]; del args[i:i + 2]
    if '--out' in args:
        i = args.index('--out'); outdir = args[i + 1]; del args[i:i + 2]
    if not os.path.exists(TSV):
        sys.exit('%s missing -- run parse_legoo.py first' % TSV)

    # acronym + alternatives per gene, from the parse
    want = {}
    for i, ln in enumerate(io.open(TSV, encoding='utf-8')):
        if i == 0 or not ln.strip():
            continue
        f = ln.rstrip('\n').split('\t')
        names = [a.strip() for a in (f[2] or '').split('|') if a.strip()]
        if names:
            want[f[0]] = names

    # genes whose LeGOO xref is NOT the display xref -> their display_xref_id
    rows = mysql("""
        SELECT g.stable_id, g.display_xref_id
          FROM gene g
          JOIN object_xref ox ON ox.ensembl_id=g.gene_id AND ox.ensembl_object_type='Gene'
          JOIN xref x ON x.xref_id=ox.xref_id
          JOIN external_db e ON e.external_db_id=x.external_db_id AND e.db_name='LeGOO'
         WHERE g.display_xref_id IS NOT NULL AND g.display_xref_id <> x.xref_id""", core)
    targets = {r[0]: int(r[1]) for r in rows if len(r) == 2 and r[1] != 'NULL'}
    sys.stderr.write('genes keeping their own display name: %d\n' % len(targets))
    if not targets:
        sys.exit('nothing to do')

    # what those display xrefs already carry, so we neither collide nor claim rows we did not add
    existing = set()
    ids = ','.join(str(v) for v in sorted(set(targets.values())))
    for r in mysql("SELECT xref_id, synonym FROM external_synonym WHERE xref_id IN (%s)" % ids,
                   core):
        if len(r) == 2:
            existing.add((int(r[0]), r[1]))
    sys.stderr.write('synonym rows already on those xrefs: %d\n' % len(existing))

    pairs, skipped = [], 0
    for sid, xid in sorted(targets.items()):
        for name in want.get(sid, []):
            if (xid, name) in existing or (xid, name) in pairs:
                skipped += 1
                continue
            pairs.append((xid, name))
    sys.stderr.write('synonym rows to add: %d  (already present, skipped: %d)\n'
                     % (len(pairs), skipped))
    if not pairs:
        sys.exit('nothing to add')

    if not os.path.isdir(outdir):
        os.makedirs(outdir)
    hdr = ("-- GENERATED by legoo/gen_display_synonyms_sql.py -- do not edit by hand.\n"
           "-- target: %s\n"
           "-- Makes the LeGOO acronym searchable for the %d genes that kept their own display\n"
           "-- name. dump_genes.js reads synonyms only from the display xref, so without this\n"
           "-- those %d values never reach the search index.\n\n"
           % (core, len(targets), len(pairs)))

    w = io.open(os.path.join(outdir, '04_legoo_display_synonyms.sql'), 'w', encoding='utf-8')
    w.write(hdr)
    w.write("SELECT IF((SELECT COUNT(*) FROM external_db WHERE db_name='LeGOO')=1,\n"
            "          'OK','ABORT: run 03_legoo_load.sql first') AS legoo_loaded;\n\n")
    for i in range(0, len(pairs), 500):
        w.write("INSERT IGNORE INTO external_synonym (xref_id, synonym) VALUES\n")
        w.write(',\n'.join("  (%d,%s)" % (x, q(n)) for x, n in pairs[i:i + 500]))
        w.write(";\n")
    w.write("\nSELECT 'synonym rows now on those display xrefs', COUNT(*), %d AS expected_added\n"
            "  FROM external_synonym WHERE xref_id IN (%s);\n" % (len(pairs) + len(existing), ids))
    w.close()

    w = io.open(os.path.join(outdir, '98_legoo_display_synonyms_revert.sql'), 'w',
                encoding='utf-8')
    w.write(hdr.replace('Makes', 'Reverts'))
    w.write("-- Deletes exactly the %d pairs 04 added; rows that already existed are untouched.\n\n"
            % len(pairs))
    for i in range(0, len(pairs), 300):
        w.write("DELETE FROM external_synonym WHERE (xref_id, synonym) IN (\n")
        w.write(',\n'.join("  (%d,%s)" % (x, q(n)) for x, n in pairs[i:i + 300]))
        w.write(");\n")
    w.close()
    sys.stderr.write('wrote %s/04_legoo_display_synonyms.sql and '
                     '98_legoo_display_synonyms_revert.sql\n' % outdir)


if __name__ == '__main__':
    main()
